export interface CatalogCategory {
  name: string;
  slug: string;
  sector: string;
  description: string;
}

export function slugifyCategory(name: string): string {
  return name
    .toLowerCase()
    .replace(/[&/\\#,+()$~%.'":*?<>{}]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

