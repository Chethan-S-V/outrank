// Flatten and deduplicate catalog
export const ALL_CATALOG_CATEGORIES: CatalogCategory[] = (() => {
  const seen = new Set<string>();
  const list: CatalogCategory[] = [];

  for (const [sector, names] of Object.entries(CATEGORY_SECTORS)) {
    for (const name of names) {
      const slug = slugifyCategory(name);
      if (!seen.has(slug)) {
        seen.add(slug);
        list.push({
          name,
          slug,
          sector,
          description: `Verified platforms, applications, and sovereign creators in ${name}.`,
        });
      }
    }
  }

  return list;
})();
